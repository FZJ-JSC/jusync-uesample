static TAutoConsoleVariable<float> CVarJusyncVolumeOpacity(
    TEXT("jusync.Volume.Opacity"), 1.2f,
    TEXT("Optical depth one fully dense voxel contributes. Raise until the dense core reads solid; ~1.2 for three-voxel walls."));

static TAutoConsoleVariable<float> CVarJusyncVolumeDensity(
    TEXT("jusync.Volume.Density"), 2.0f,
    TEXT("Multiplier on normalised voxel density before the threshold."));

static TAutoConsoleVariable<float> CVarJusyncVolumeContrast(
    TEXT("jusync.Volume.Contrast"), 8.0f,
    TEXT("Steepness of the isosurface ramp. This sets how wide the soft band around the surface is, so low values read as glow."));

static TAutoConsoleVariable<float> CVarJusyncVolumeErosion(
    TEXT("jusync.Volume.Erosion"), 0.0f,
    TEXT("How much of the noise field carves the surface away. 0 keeps the field as voxelized; raise for a wispy look."));

static TAutoConsoleVariable<float> CVarJusyncVolumeNoiseScale(
    TEXT("jusync.Volume.NoiseScale"), 16.0f,
    TEXT("Noise cycles across the volume; low gives blobby lumps, 15-20 gives fine surface detail."));

// UE 5.7 leaves PostProcessSettings.BloomThreshold at -1 (derived from exposure), so
// there is no fixed luminance the march can target. The material is unlit, so this
// scales everything the volume itself emits and keeps it out of the bloom pile-up
// without changing the level's own post processing.
static TAutoConsoleVariable<float> CVarJusyncVolumeGain(
    TEXT("jusync.Volume.Gain"), 0.03f,
    TEXT("Scale on the volume's emissive output; lower it if the volume still blooms."));

// Instrumentation rather than a look control. Every stage between the voxel upload and
// the density ramp has failed at some point and looked identical from outside, so this
// lets one screenshot tell them apart.
static TAutoConsoleVariable<float> CVarJusyncVolumeDebug(
    TEXT("jusync.Volume.Debug"), 0.0f,
    TEXT("0 = normal, 1 = show the march's own state instead of the volume: red is the brightest density sampled, green is 1 wherever the box covered a pixel, blue is the brightest density after the ramp. 2 = show the accumulated colour at full opacity, which separates a dead colour channel from a dead opacity channel. 3 = show the marched segment length, red for a full box traversal and green for a degenerate one. Green alone at level 1 means the texture arrived empty; red with no blue means the ramp rejected the field."));

namespace
{
    // Cheap change detector for the tuning cvars, so a changed value can be pushed
    // without re-reading every one of them each tick.
    uint32 VolumeCVarSignature()
    {
        const float Values[] = {
            CVarJusyncVolumeOpacity.GetValueOnGameThread(),
            CVarJusyncVolumeDensity.GetValueOnGameThread(),
            CVarJusyncVolumeContrast.GetValueOnGameThread(),
            CVarJusyncVolumeErosion.GetValueOnGameThread(),
            CVarJusyncVolumeNoiseScale.GetValueOnGameThread(),
            CVarJusyncVolumeGain.GetValueOnGameThread(),
            CVarJusyncVolumeDebug.GetValueOnGameThread(),
        };
        uint32 Hash = 0;
        for (const float Value : Values)
        {
            Hash = Hash * 31u + GetTypeHash(Value);
        }
        return Hash;
    }

    // The material graph is generated by Tools/CreateJusyncVolumeMaterial.py and
    // the parameter store drops unknown names without complaining, so name drift
    // between the two sides shows up as an invisible volume rather than an error.
    void WarnOnParameterMismatch(const UMaterialInterface* Material)
    {
        if (!Material)
        {
            return;
        }

        auto NamesOfType = [Material](EMaterialParameterType Type)
        {
            TArray<FMaterialParameterInfo> Info;
            TArray<FGuid> Ids;
            Material->GetAllParameterInfoOfType(Type, Info, Ids);
            TSet<FName> Names;
            Names.Reserve(Info.Num());
            for (const FMaterialParameterInfo& Parameter : Info)
            {
                Names.Add(Parameter.Name);
            }
            return Names;
        };

        struct FExpected { EMaterialParameterType Type; const wchar_t* Name; };
        static const FExpected Expected[] = {
            { EMaterialParameterType::Texture, TEXT("VolumeTex") },
            { EMaterialParameterType::Vector,  TEXT("InBoxMin") },
            { EMaterialParameterType::Vector,  TEXT("InBoxMax") },
            { EMaterialParameterType::Vector,  TEXT("InVoxelSize") },
            { EMaterialParameterType::Scalar,  TEXT("InDensity") },
            { EMaterialParameterType::Scalar,  TEXT("InExtinction") },
            { EMaterialParameterType::Scalar,  TEXT("InContrast") },
            { EMaterialParameterType::Scalar,  TEXT("InErosion") },
            { EMaterialParameterType::Scalar,  TEXT("InNoiseScale") },
            { EMaterialParameterType::Scalar,  TEXT("InGain") },
            { EMaterialParameterType::Scalar,  TEXT("InDebug") },
        };

        FString Missing;
        TMap<EMaterialParameterType, TSet<FName>> NamesByType;
        for (const FExpected& Want : Expected)
        {
            if (!NamesByType.Contains(Want.Type))
            {
                NamesByType.Add(Want.Type, NamesOfType(Want.Type));
            }
            const TSet<FName>& Names = NamesByType[Want.Type];
            // An uncompiled material reports no parameters at all; stay quiet then.
            if (Names.Num() && !Names.Contains(Want.Name))
            {
                Missing += Missing.IsEmpty() ? TEXT(" ") : TEXT(", ");
                Missing += Want.Name;
            }
        }

        if (!Missing.IsEmpty())
        {
            UE_LOG(LogTemp, Warning,
                TEXT("[Volume] %s does not declare:%s - the actor's values for those are dropped silently"),
                *Material->GetName(), *Missing);
        }
    }
}

AJUSYNCVolumeActor::AJUSYNCVolumeActor()
{
    PrimaryActorTick.bCanEverTick = true;

    Box = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("VolumeBox"));
    SetRootComponent(Box);
    Box->SetMobility(EComponentMobility::Movable);
    Box->SetCollisionEnabled(ECollisionEnabled::NoCollision);
    Box->SetCollisionProfileName(TEXT("NoCollision"));
    Box->SetGenerateOverlapEvents(false);
    Box->SetCastShadow(false);
    Box->bCastDynamicShadow = false;
    Box->bCastStaticShadow = false;
    Box->SetReceivesDecals(false);

    static ConstructorHelpers::FObjectFinder<UStaticMesh> CubeMesh(TEXT("/Engine/BasicShapes/Cube.Cube"));
    if (CubeMesh.Succeeded())
    {
        Box->SetStaticMesh(CubeMesh.Object);
    }

    SetActorEnableCollision(false);
}

void AJUSYNCVolumeActor::ApplyGrid(const FJUSYNCVolumeGrid& Grid, UMaterialInterface* InMaterial)
{
    if (!Grid.IsValid() || !Box)
    {
        return;
    }

    EnsureResources(Grid.Resolution, InMaterial);

    const FBox& Bounds = Grid.Bounds;
    const FVector Size = Bounds.GetSize();
    SetActorLocation(Bounds.GetCenter());
    Box->SetWorldScale3D(Size / 100.0);

    if (VolumeMaterial)
    {
        VolumeMaterial->SetVectorParameterValue(TEXT("InBoxMin"),
            FLinearColor(Bounds.Min.X, Bounds.Min.Y, Bounds.Min.Z, 0.f));
        VolumeMaterial->SetVectorParameterValue(TEXT("InBoxMax"),
            FLinearColor(Bounds.Max.X, Bounds.Max.Y, Bounds.Max.Z, 0.f));

        LastVoxelSize = Size / FMath::Max(Grid.Resolution, 1);
        VolumeMaterial->SetVectorParameterValue(TEXT("InVoxelSize"),
            FLinearColor(LastVoxelSize.X, LastVoxelSize.Y, LastVoxelSize.Z, 0.f));
        PushMaterialParameters();
    }

    UploadVoxels(Grid);

    if (!bGridStatsLogged)
    {
        int32 Filled = 0;
        uint8 Peak = 0;
        // Mean colour and the widest per-channel span over the filled voxels: a cloud
        // coloured by FColor's White default has a span near zero, which is otherwise
        // indistinguishable from the payload's own palette.
        uint64 Sum[3] = { 0, 0, 0 };
        uint8 Low[3] = { 255, 255, 255 };
        uint8 High[3] = { 0, 0, 0 };
        for (int32 I = 0; I + 3 < Grid.Voxels.Num(); I += 4)
        {
            const uint8 Alpha = Grid.Voxels[I + 3];
            if (Alpha == 0)
            {
                continue;
            }
            ++Filled;
            Peak = FMath::Max(Peak, Alpha);
            for (int32 C = 0; C < 3; ++C)
            {
                const uint8 V = Grid.Voxels[I + C];
                Sum[C] += V;
                Low[C] = FMath::Min(Low[C], V);
                High[C] = FMath::Max(High[C], V);
            }
        }

        int32 MaxSpan = 0;
        for (int32 C = 0; C < 3; ++C)
        {
            MaxSpan = FMath::Max(MaxSpan, int32(High[C]) - int32(Low[C]));
        }
        const FVector Mean = Filled > 0
            ? FVector(double(Sum[0]) / Filled, double(Sum[1]) / Filled, double(Sum[2]) / Filled) / 255.0
            : FVector::ZeroVector;
        UE_LOG(LogTemp, Display,
            TEXT("[Volume] %d^3 grid, box %.1f x %.1f x %.1f cm at (%.0f, %.0f, %.0f)  |  density peak %u, %d/%d voxels (%.1f%%)  |  colour mean (%.2f,%.2f,%.2f) span %d  |  material %s"),
            Grid.Resolution, Size.X, Size.Y, Size.Z,
            Bounds.GetCenter().X, Bounds.GetCenter().Y, Bounds.GetCenter().Z,
            Peak, Filled, Grid.Voxels.Num() / 4,
            100.0 * Filled / FMath::Max(1, Grid.Voxels.Num() / 4),
            Mean.X, Mean.Y, Mean.Z, MaxSpan,
            VolumeMaterial ? *VolumeMaterial->GetName() : TEXT("NULL"));
        bGridStatsLogged = true;
    }
}

void AJUSYNCVolumeActor::PushMaterialParameters()
{
    if (!VolumeMaterial)
    {
        return;
    }

    // Extinction is tracked per voxel rather than per cm, so the look survives
    // a resolution or scale change: jusync.Volume.Opacity says how opaque one
    // fully dense voxel is.
    VolumeMaterial->SetScalarParameterValue(TEXT("InExtinction"),
        CVarJusyncVolumeOpacity.GetValueOnGameThread() / FMath::Max(LastVoxelSize.GetMax(), 1e-3f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InDensity"),
        FMath::Max(CVarJusyncVolumeDensity.GetValueOnGameThread(), 0.0f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InContrast"),
        FMath::Max(CVarJusyncVolumeContrast.GetValueOnGameThread(), 0.0f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InErosion"),
        FMath::Clamp(CVarJusyncVolumeErosion.GetValueOnGameThread(), 0.0f, 2.0f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InNoiseScale"),
        FMath::Clamp(CVarJusyncVolumeNoiseScale.GetValueOnGameThread(), 0.5f, 64.0f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InGain"),
        FMath::Clamp(CVarJusyncVolumeGain.GetValueOnGameThread(), 0.0f, 4.0f));
    VolumeMaterial->SetScalarParameterValue(TEXT("InDebug"),
        FMath::Clamp(CVarJusyncVolumeDebug.GetValueOnGameThread(), 0.0f, 3.0f));

    ParameterSignature = VolumeCVarSignature();
}

void AJUSYNCVolumeActor::Tick(float DeltaSeconds)
{
    Super::Tick(DeltaSeconds);

    // Otherwise a changed jusync.Volume.* value sits unread until the next grid
    // arrives, which on a finished or paused stream means never.
    if (VolumeMaterial && VolumeCVarSignature() != ParameterSignature)
    {
        PushMaterialParameters();
    }
}

void AJUSYNCVolumeActor::EnsureResources(int32 Resolution, UMaterialInterface* InMaterial)
{
    if (!VolumeTarget || TextureSize != Resolution)
    {
        VolumeTarget = NewObject<UTextureRenderTargetVolume>(this);
        VolumeTarget->ClearColor = FLinearColor::Black;
        VolumeTarget->bForceLinearGamma = true;
        VolumeTarget->Init(Resolution, Resolution, Resolution, PF_B8G8R8A8);
        VolumeTarget->UpdateResourceImmediate(true);
        TextureSize = Resolution;

        if (VolumeMaterial)
        {
            VolumeMaterial->SetTextureParameterValue(TEXT("VolumeTex"), VolumeTarget);
        }
    }

    if (InMaterial && (!VolumeMaterial || VolumeMaterial->Parent != InMaterial))
    {
        VolumeMaterial = UMaterialInstanceDynamic::Create(InMaterial, this);
        VolumeMaterial->SetTextureParameterValue(TEXT("VolumeTex"), VolumeTarget);
        Box->SetMaterial(0, VolumeMaterial);
        WarnOnParameterMismatch(InMaterial);
    }
}

void AJUSYNCVolumeActor::UploadVoxels(const FJUSYNCVolumeGrid& Grid)
{
    if (!VolumeTarget)
    {
        return;
    }

    // GetRenderTargetResource() asserts on the game thread; this is its game-thread
    // accessor (engine does the same in WidgetRenderer). The texture is resolved
    // inside the command, and a queued command cannot outrun the resource's own
    // render-thread release.
    FTextureRenderTargetResource* Resource = VolumeTarget->GameThread_GetRenderTargetResource();
    if (!Resource)
    {
        return;
    }

    const uint32 Res = static_cast<uint32>(Grid.Resolution);
    if (Grid.Voxels.Num() < static_cast<int32>(Res * Res * Res * 4))
    {
        return;
    }

    TArray<uint8> Data = Grid.Voxels;

    ENQUEUE_RENDER_COMMAND(JUSYNCVolumeUpload)(
        [Resource, Data = MoveTemp(Data), Res](FRHICommandListImmediate& RHICmdList)
        {
            const FTextureRHIRef Target = Resource->GetRenderTargetTexture();
            if (Target.IsValid())
            {
                const FUpdateTextureRegion3D Region(0, 0, 0, 0, 0, 0, Res, Res, Res);
                RHICmdList.UpdateTexture3D(Target, 0, Region, Res * 4, Res * Res * 4, Data.GetData());
            }
            else
            {
                static bool bWarnedOnce = false;
                if (!bWarnedOnce)
                {
                    bWarnedOnce = true;
                    UE_LOG(LogTemp, Warning,
                        TEXT("[Volume] render target has no texture on the render thread; density not uploaded"));
                }
            }
        });
}
